package cafe;

public class sanpham {
    private String masp;
    private String tensp;
    private double dongia;
    private String khuyenmai;
    private String trangthai;
    private String loaisanpham;

    public String getMasp() { return masp; }
    public void setMasp(String masp) { this.masp = masp; }

    public String getTensp() { return tensp; }
    public void setTensp(String tensp) { this.tensp = tensp; }

    public double getDongia() { return dongia; }
    public void setDongia(double dongia) { this.dongia = dongia; }

    public String getKhuyenmai() { return khuyenmai; }
    public void setKhuyenmai(String khuyenmai) { this.khuyenmai = khuyenmai; }

    public String getTrangthai() { return trangthai; }
    public void setTrangthai(String trangthai) { this.trangthai = trangthai; }

    public String getLoaisanpham() { return loaisanpham; }
    public void setLoaisanpham(String loaisanpham) { this.loaisanpham = loaisanpham; }
}
